#!/usr/bin/env node
/**
 * Dependency license audit (docs/ARCHITECTURE.md §16, "Dependency licenses and security
 * scans are reviewed").
 *
 * Every dependency's license is listed and checked against an allow-list, because
 * a license obligation is a legal commitment the project makes by shipping — and
 * because the alternative to a list is discovering a copyleft dependency in a
 * release note.
 *
 * Three tiers rather than pass/fail:
 *
 *   - **allow** — permissive, no obligation beyond attribution.
 *   - **review** — permissive but with a condition worth a human glance (weak
 *     copyleft, or a compound expression that cannot be classified by string
 *     matching alone).
 *   - **deny** — strong copyleft or absent. Fails the build.
 *
 * The `review` tier is the one that earns its place. Compound expressions such as
 * `Apache-2.0 AND LGPL-3.0-or-later` cannot be judged by matching a license name,
 * and silently allowing them is how a project acquires an obligation nobody read.
 * They are printed with the packages that carry them, so the review is a
 * five-minute read rather than an archaeology project.
 *
 * Usage:
 *   node scripts/audit-licenses.mjs            # report; exits 1 on a denied license
 *   node scripts/audit-licenses.mjs --write    # also write docs/dependency-licenses.md
 */
import { execFileSync } from "node:child_process"
import { existsSync, mkdirSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, "..")

/** Permissive: attribution only. */
const ALLOW = new Set([
  "MIT",
  "MIT-0",
  "ISC",
  "Apache-2.0",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "0BSD",
  "BlueOak-1.0.0",
  "CC0-1.0",
  "Unlicense",
  "Python-2.0",
  "PostgreSQL",
  "Zlib",
])

/**
 * Permissive-ish, but each carries a condition, or is an expression a string match
 * cannot classify. Reported, not failed: the point is that a person reads them.
 */
const REVIEW = [
  // Compounds: SPDX expressions, not single licenses.
  / AND | OR | WITH /,
  // Weak copyleft: fine in most distributions, obligations on modified files.
  /^MPL-2\.0$/,
  /^LGPL-[23]\.\d(-only|-or-later)?$/,
  /^EPL-[12]\.0$/,
  /^CDDL-1\.[01]$/,
  // Documentation / data licenses that are not software licenses.
  /^CC-BY-4\.0$/,
]

/** Strong copyleft, or unknown. These fail. */
const DENY = [
  /^GPL-[23]\.\d(-only|-or-later)?$/,
  /^AGPL-/,
  /^SSPL-/,
  /^BUSL-/,
  /^UNLICENSED$/,
  /^UNKNOWN$/,
]

/**
 * `pnpm licenses list --json` groups packages by license. It is the only
 * dependency here — no license-checking library, because the classification is
 * three regular expressions and a set, and a library would be a supply-chain
 * dependency added to audit the supply chain.
 */
function inventory() {
  // `shell: true` is required on Windows, where `pnpm` is a `.cmd` shim that
  // `execFileSync` cannot execute directly. Without it this fails with ENOENT
  // and looks like pnpm is missing.
  const stdout = execFileSync("pnpm", ["licenses", "list", "--json"], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
    shell: process.platform === "win32",
  })
  return JSON.parse(stdout)
}

const classify = (license) => {
  const name = (license ?? "UNKNOWN").trim()
  if (ALLOW.has(name)) return { tier: "allow", name }
  if (DENY.some((pattern) => pattern.test(name))) return { tier: "deny", name }
  if (REVIEW.some((pattern) => pattern.test(name))) return { tier: "review", name }
  return { tier: "review", name }
}

const reported = inventory()

const rows = []
for (const [license, packages] of Object.entries(reported)) {
  const { tier, name } = classify(license)
  rows.push({
    license: name,
    tier,
    packages: packages.map((entry) => `${entry.name}@${entry.version ?? ""}`),
  })
}
rows.sort((a, b) => a.tier.localeCompare(b.tier) || b.packages.length - a.packages.length)

const total = rows.reduce((sum, row) => sum + row.packages.length, 0)
const denied = rows.filter((row) => row.tier === "deny")
const forReview = rows.filter((row) => row.tier === "review")

const lines = []
lines.push("# Dependency licenses")
lines.push("")
lines.push(
  `Generated by \`scripts/audit-licenses.mjs\` from \`pnpm licenses list --json\`. ${total} packages across ${rows.length} license expressions.`,
)
lines.push("")
lines.push(
  "The audit is part of §16's release gate. Licenses are classified into three tiers: allowed, needs review, and denied. A denied license fails the build; a license needing review is listed here so it is read by a person rather than allowed by a string match.",
)
lines.push("")
lines.push("## Needs review")
lines.push("")
if (forReview.length === 0) {
  lines.push("None. Every license is permissive and unrestricted.")
} else {
  for (const row of forReview) {
    lines.push(`### \`${row.license}\` — ${row.packages.length} package(s)`)
    lines.push("")
    for (const name of row.packages.slice(0, 20)) lines.push(`- ${name}`)
    if (row.packages.length > 20) lines.push(`- …and ${row.packages.length - 20} more`)
    lines.push("")
  }
}
lines.push("## Allowed")
lines.push("")
lines.push("| License | Packages |")
lines.push("|---|---|")
for (const row of rows.filter((entry) => entry.tier === "allow")) {
  lines.push(`| \`${row.license}\` | ${row.packages.length} |`)
}
lines.push("")

const output = lines.join("\n")

if (process.argv.includes("--write")) {
  const target = join(repoRoot, "docs")
  if (!existsSync(target)) mkdirSync(target, { recursive: true })
  writeFileSync(join(target, "dependency-licenses.md"), output)
  console.log(`[licenses] wrote ${join("docs", "dependency-licenses.md")}`)
}

const write = (line) => process.stdout.write(`${line}\n`)
write(`[licenses] ${total} packages, ${rows.length} license expressions`)
for (const row of forReview) {
  write(`  review  ${row.license} (${row.packages.length}): ${row.packages.slice(0, 3).join(", ")}`)
}
for (const row of denied) {
  write(`  DENIED  ${row.license} (${row.packages.length}): ${row.packages.join(", ")}`)
}

if (denied.length > 0) {
  write("[licenses] a denied license is present; remove or replace it before release.")
  process.exit(1)
}
write("[licenses] no denied license")
