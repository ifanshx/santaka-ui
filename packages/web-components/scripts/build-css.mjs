/**
 * Build the component stylesheet.
 *
 * Section 4, Distribution and exports contract: "No JavaScript injects a
 * `<style>` or `<link>` tag at runtime, because that breaks SSR extraction,
 * defeats Tailwind/PostCSS processing, and re-introduces FOUC."
 *
 * Stencil's default is the opposite — it inlines each component's CSS into the
 * JS bundle and injects a `<style data-styles>` element at hydration time. That
 * is exactly the mechanism the plan rules out, and it is also why this package
 * ships no `styles` in any `@Component` decorator.
 *
 * So component CSS lives here as plain `.css` files, keyed off `data-slot`
 * hooks (ADR-011, scoped styles rather than Shadow DOM), and this script
 * concatenates them into one stylesheet that consumers import explicitly:
 *
 *   import "@santaka-ui/web-components/santaka.css"
 *
 * The benefit is not theoretical: the same file works with SSR extraction,
 * survives a JS-disabled paint, is post-processable by Tailwind/PostCSS, and
 * carries no hydration boundary.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const pkgRoot = resolve(here, "..")
const componentsDir = join(pkgRoot, "src", "components")
const outDir = join(pkgRoot, "dist")
const outFile = join(outDir, "santaka.css")

function componentCssFiles() {
  return readdirSync(componentsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => join(componentsDir, entry.name, `${entry.name}.css`))
    .filter((path) => {
      try {
        readFileSync(path)
        return true
      } catch {
        return false
      }
    })
    .sort()
}

/**
 * Every color in component CSS must be a token with a literal fallback. A bare
 * `var(--sk-...)` with no fallback renders as *no declaration at all* when a
 * consumer forgets the theme import, which is the failure mode section 4 calls
 * out as unacceptable.
 */
const TOKEN_REFERENCE = /var\(\s*(--sk-[a-z0-9-]+)(\s*[,)])/g

function assertFallbacks(css, defined, source) {
  const problems = []
  for (const match of css.matchAll(TOKEN_REFERENCE)) {
    if (match[2] === ",") continue
    if (defined.has(match[1])) continue
    problems.push(`  ${match[1]} (${source})`)
  }
  if (problems.length > 0) {
    throw new Error(
      `[web-components] token references without a literal fallback:\n${[...new Set(problems)].join("\n")}`,
    )
  }
}

const banner = `/*
 * Santaka UI — component styles.
 *
 * Generated by scripts/build-css.mjs from the component sources. DO NOT EDIT.
 *
 * Import after the token themes:
 *
 *   @import "@santaka-ui/tokens/css/index.css";
 *   @import "@santaka-ui/web-components/santaka.css";
 *
 * Components use scoped styles with data-slot hooks rather than Shadow DOM
 * (ADR-011), so this file reaches component internals and consumer overrides
 * reach the components.
 */
`

const files = componentCssFiles()
if (files.length === 0) {
  throw new Error("[web-components] no component stylesheets found")
}

const sections = files.map((path) => readFileSync(path, "utf8").trim())

// Component CSS may declare its own `--sk-button-*` aliases (the variant
// indirection layer). Those are declared in the same file, so they count as
// defined for this check; a bare reference to a token nobody declares is still
// an error.
const declared = new Set(
  sections.flatMap((css) => [...css.matchAll(/^\s*(--sk-[a-z0-9-]+)\s*:/gm)].map((m) => m[1])),
)
for (const path of files) {
  assertFallbacks(readFileSync(path, "utf8"), declared, path.slice(pkgRoot.length + 1))
}

mkdirSync(outDir, { recursive: true })
const output = `${banner}\n${sections.join("\n\n")}\n`
writeFileSync(outFile, output)

const componentCount = files.length
const selectors = new Set([...output.matchAll(/^(sk-[\w-]+)/gm)].map((m) => m[1]))
console.log(
  `[web-components] wrote ${outFile} (${componentCount} components, ${selectors.size} block selectors)`,
)
