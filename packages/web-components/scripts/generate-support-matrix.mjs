#!/usr/bin/env node
/**
 * Generate the browser support matrix from the Playwright projects that
 * actually run (`docs/ARCHITECTURE.md` §4 and §16: "The documented support matrix is
 * generated from the Playwright projects that actually run, not hand-
 * maintained. Adding a browser to the documentation without a test job is a
 * release blocker.").
 *
 * The matrix is *derived*, not typed. A browser appears in it only if a
 * Playwright project launches it, and the revision shown is the one Playwright
 * will actually launch — read from the installed browser, not copied from a
 * manifest that could disagree with it.
 *
 * What the document deliberately does NOT contain is a per-engine pass/fail
 * column. That was the first design and it does not survive CI: the result is
 * volatile, so a committed "passed" is either stale or re-verified by running
 * all three engines on every CI run, and a document that drifts is worse than
 * one that says less. The evidence that each engine is tested is that the
 * `browsers` matrix job in `.github/workflows/ci.yml` runs it — a fact the
 * document states and a reader can check. The document's job is the stable
 * claim: which engines, at which revisions, against which tier floors.
 *
 * Usage:
 *   node scripts/generate-support-matrix.mjs           # write docs/browser-support.md
 *   node scripts/generate-support-matrix.mjs --stdout  # print, do not write
 *   node scripts/generate-support-matrix.mjs --check   # exit 1 if the file drifts
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const pkgRoot = resolve(here, "..")
const repoRoot = resolve(pkgRoot, "..", "..")

const OUT_PATH = join(repoRoot, "docs", "browser-support.md")

/** ADR-014's two tiers, with what each one means. Values are the floors. */
const TIERS = [
  {
    name: "Baseline",
    meaning: "Full styling, motion, and behavior",
    floors: { chromium: "111", firefox: "128", webkit: "16.4" },
  },
  {
    name: "Core",
    meaning: "Structure and behavior; degraded styling",
    floors: { chromium: "90", firefox: "121", webkit: "15.4" },
  },
]

const ENGINE_LABEL = {
  chromium: "Chromium (Chrome / Edge)",
  firefox: "Firefox",
  webkit: "WebKit (Safari)",
}

/** Which engine a Playwright project launches, from its name. */
function engineOf(projectName) {
  if (projectName.startsWith("chromium")) return "chromium"
  if (projectName.startsWith("firefox")) return "firefox"
  if (projectName.startsWith("webkit")) return "webkit"
  return null
}

/**
 * Read the project list out of `playwright.config.ts` rather than importing it,
 * because importing the config would start its `webServer` and require a built
 * package. The parse is narrow on purpose: a `name: "…"` inside the `projects`
 * array.
 */
function projectsFromConfig() {
  const source = readFileSync(join(pkgRoot, "playwright.config.ts"), "utf8")
  const names = [...source.matchAll(/name:\s*"([^"]+)"/g)].map((m) => m[1])
  // The `visual` project photographs baselines; ADR-019 calls it a test layer,
  // not a browser tier, and a support matrix answers "which browsers run this
  // library", not "which test layers exist".
  return names.filter((name) => name !== "visual")
}

/**
 * Browser revisions, read from the browsers Playwright will actually launch.
 * `executablePath()` returns `…/chromium-1248/chrome-linux/chrome`, so the
 * revision segment is the real pin. Reading `browsers.json` directly is not an
 * option: `playwright-core` is transitive and does not export that file.
 */
async function browserRevisions() {
  const { chromium, firefox, webkit } = await import("@playwright/test")
  const revisions = {}
  for (const [name, browser] of Object.entries({ chromium, firefox, webkit })) {
    try {
      const match = browser.executablePath().match(new RegExp(`${name}-(\\d+)`))
      if (match) revisions[name] = match[1]
    } catch {
      // Not installed: no revision to report. The caller decides whether that
      // is acceptable (see main).
    }
  }
  return revisions
}

function render(projects, revisions) {
  const engineProjects = new Map()
  for (const project of projects) {
    const engine = engineOf(project)
    if (!engine) continue
    if (!engineProjects.has(engine)) engineProjects.set(engine, [])
    engineProjects.get(engine).push(project)
  }

  const lines = []
  lines.push("# Browser support")
  lines.push("")
  lines.push("<!-- Generated by packages/web-components/scripts/generate-support-matrix.mjs.")
  lines.push("     Do not edit by hand. The matrix is derived from the Playwright projects")
  lines.push("     that actually run, so a browser appears here only if a project launches it.")
  lines.push("     Regenerate with `pnpm --filter @santaka-ui/web-components support-matrix`. -->")
  lines.push("")
  lines.push("Two tiers (ADR-014). **Baseline** gets full styling, motion, and behavior.")
  lines.push("**Core** gets structure and behavior with degraded styling: a feature Baseline")
  lines.push("uses freely is either avoided in component CSS or placed behind `@supports`, so")
  lines.push("a Core browser keeps a working fallback.")
  lines.push("")
  lines.push("Only Baseline is launched by a Playwright project. Core is the floor the CSS is")
  lines.push("written to, and it is enforced by the conformance test in")
  lines.push("`e2e/conventions.e2e.ts` — which fails on a Baseline-only feature used outside")
  lines.push("an `@supports` block — rather than by running a Core-tier browser. Playwright")
  lines.push("bundles one revision per engine and cannot launch Chrome 90, Firefox 121, or")
  lines.push("Safari 15.4, so a claim that Core is *tested* would not survive a reader")
  lines.push("checking it. The discipline is checked; the rendering is not.")

  lines.push("")
  lines.push("| Tier | Meaning | " + Object.values(ENGINE_LABEL).join(" | ") + " |")
  lines.push(
    "|---|---|" +
      Object.keys(ENGINE_LABEL)
        .map(() => "---")
        .join("|") +
      "|",
  )
  for (const tier of TIERS) {
    const cells = Object.keys(ENGINE_LABEL).map((engine) => tier.floors[engine] ?? "—")
    lines.push(`| ${tier.name} | ${tier.meaning} | ${cells.join(" | ")} |`)
  }
  lines.push("")
  lines.push("The floors above are what each tier *guarantees*. What the suite launches is the")
  lines.push("browser revision Playwright bundles, pinned by the lockfile:")
  lines.push("")
  lines.push("| Engine | Playwright project | Bundled revision | Runs in CI |")
  lines.push("|---|---|---|---|")
  for (const [engine, engineProjectList] of engineProjects) {
    const revision = revisions[engine] ? `\`${engine}-${revisions[engine]}\`` : "—"
    for (const project of engineProjectList) {
      lines.push(`| ${ENGINE_LABEL[engine]} | \`${project}\` | ${revision} | \`browsers\` job |`)
    }
  }
  lines.push("")
  lines.push("## Test layers")
  lines.push("")
  lines.push("Playwright also runs a `visual` project (ADR-019), which photographs example")
  lines.push("sections rather than asserting behavior. It is a test layer, not a browser tier,")
  lines.push("and it is deliberately excluded from the table above.")
  lines.push("")
  return lines.join("\n")
}

const argv = process.argv.slice(2)
const toStdout = argv.includes("--stdout")
const check = argv.includes("--check")

const projects = projectsFromConfig()
const revisions = await browserRevisions()

if (check) {
  // A missing revision means the browser is not installed, so the document
  // cannot be reproduced faithfully. In CI the browsers are installed before
  // this runs; locally, `--check` is meaningful only after
  // `playwright install chromium firefox webkit`.
  const missing = ["chromium", "firefox", "webkit"].filter((engine) => !revisions[engine])
  if (missing.length > 0) {
    console.error(
      `[support-matrix] cannot check: ${missing.join(", ")} not installed. ` +
        "Run `pnpm --filter @santaka-ui/web-components exec playwright install chromium firefox webkit`.",
    )
    process.exit(1)
  }

  const expected = render(projects, revisions)
  let actual = ""
  try {
    actual = readFileSync(OUT_PATH, "utf8")
  } catch {
    console.error(`[support-matrix] ${OUT_PATH} is missing. Run \`support-matrix\` to write it.`)
    process.exit(1)
  }
  if (actual !== expected) {
    console.error(
      "[support-matrix] docs/browser-support.md is out of date with the Playwright config.",
    )
    console.error(
      "[support-matrix] Regenerate: pnpm --filter @santaka-ui/web-components support-matrix",
    )
    process.exit(1)
  }
  console.log("[support-matrix] docs/browser-support.md matches the Playwright config.")
  process.exit(0)
}

const output = render(projects, revisions)
if (toStdout) {
  process.stdout.write(output)
} else {
  writeFileSync(OUT_PATH, output)
  console.log(`[support-matrix] wrote ${OUT_PATH}`)
  console.log(`[support-matrix] projects: ${projects.join(", ")}`)
}
