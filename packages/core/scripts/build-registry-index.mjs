/**
 * Build the registry index — every shipped entry in one file.
 *
 * `registry/*.json` is one file per component, which is what a consumer
 * fetching a single component wants and what the CLI's `add` command diffs
 * against. The MCP server (section 11) and the CLI's `list` want the opposite:
 * the whole set at once, validated, with no filesystem walking. Rather than have
 * each consumer walk the directory — and each get it subtly wrong, or read an
 * entry without validating it — the build writes both shapes from one pass.
 *
 * The index is generated, so it cannot disagree with the per-component files.
 * It is committed alongside them for the same reason they are: a published
 * package should not require the build to be readable.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const coreRoot = resolve(here, "..")
const registryDir = join(coreRoot, "registry")
const outFile = join(registryDir, "index.json")

const entryFiles = readdirSync(registryDir)
  .filter((name) => name.endsWith(".json") && name !== "index.json")
  .sort()

const items = entryFiles.map((name) => JSON.parse(readFileSync(join(registryDir, name), "utf8")))

const index = {
  $schema: "./index.schema.json",
  schemaVersion: 1,
  generatedFrom: entryFiles,
  items,
}

writeFileSync(outFile, `${JSON.stringify(index, null, 2)}\n`)
console.log(`[registry] wrote ${outFile} (${items.length} items)`)

// The index schema is written here, not checked in by hand, because `clean`
// removes the whole `schema/` directory (`rimraf dist schema`) — a hand-authored
// file there survives until the first clean build and then disappears, which is
// the kind of failure that only shows up on someone else's machine.
const schemaDir = join(coreRoot, "schema")
const indexSchema = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  $id: "https://santaka.dev/schema/registry-index-v1.json",
  title: "Santaka UI registry index",
  description:
    "Every shipped registry entry in one document. Generated by packages/core/scripts/build-registry-index.mjs; do not edit by hand.",
  type: "object",
  required: ["schemaVersion", "items"],
  additionalProperties: false,
  properties: {
    $schema: { type: "string" },
    schemaVersion: { const: 1 },
    generatedFrom: {
      type: "array",
      items: { type: "string" },
      description:
        "The per-component files this index was built from, so a reader can see what is covered.",
    },
    items: {
      type: "array",
      items: { $ref: "./registry-item-v1.json" },
      minItems: 1,
    },
  },
}
writeFileSync(
  join(schemaDir, "registry-index-v1.json"),
  `${JSON.stringify(indexSchema, null, 2)}\n`,
)
console.log(`[registry] wrote ${join(schemaDir, "registry-index-v1.json")}`)
