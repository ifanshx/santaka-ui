#!/usr/bin/env node
/**
 * Compile the registry validator ahead of time (docs/ARCHITECTURE.md §12 budget:
 * `@santaka-ui/tokens` + `@santaka-ui/core` ≤ 8 KB).
 *
 * `validateRegistryItem` used to import Ajv at runtime and compile the schema
 * on module load. Ajv is a fine library and the wrong shape of dependency here:
 * measured through esbuild, the `validateRegistryItem` import path was **41.2 KB
 * gzipped**, of which the registry, the constants, and the schema itself account
 * for about 1.4 KB. Every CLI invocation that touches a registry entry — which
 * is every invocation — paid for a general-purpose JSON Schema engine it uses
 * for exactly one schema that never changes at runtime.
 *
 * Ajv's standalone mode emits the same compiled validator as plain JavaScript
 * with no Ajv in the output: **5.3 KB gzipped**, a 35.9 KB saving. The generated
 * file is the schema's own validation code, not a reimplementation, so the
 * acceptance and rejection behavior is identical by construction; the tests in
 * `validate-item.test.ts` are what proves it after the swap.
 *
 * Ajv stays a devDependency: it runs here, at build time, and never ships.
 */
import { createRequire } from "node:module"
import { mkdirSync, writeFileSync } from "node:fs"
import * as esbuild from "esbuild"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const pkgRoot = resolve(here, "..")
// Written into `src/` *and* `dist/`. `src/` is what `tsc` compiles and what
// vitest runs, so tests exercise the same generated code that ships; `dist/` is
// written here too because `tsc` does not copy `.js` into `outDir`. A build
// that only produced `dist/` would leave the test suite importing a file that
// does not exist — which is exactly how this was caught.
const srcFile = join(pkgRoot, "src", "registry-item-validator.js")
const outFile = join(pkgRoot, "dist", "registry-item-validator.js")

// Ajv and its standalone generator are CommonJS; this package is ESM.
const require = createRequire(import.meta.url)
const Ajv2020 = require("ajv/dist/2020.js")
const standalone = require("ajv/dist/standalone/index.js")

// The schema is read from `src/`, not from `dist/`, so this script can run
// before `tsc` — which it must, because `verify` typechecks and tests before it
// builds. `emit-schema.mjs` compiles the schema module for the JSON artifact;
// this needs only the object, and Ajv can consume the TypeScript module through
// esbuild without a build step in between.
const schemaSource = await esbuild.build({
  entryPoints: [join(pkgRoot, "src", "registry-item-schema.ts")],
  bundle: true,
  write: false,
  format: "esm",
  platform: "node",
})
const { registryItemSchema } = await import(
  `data:text/javascript;base64,${Buffer.from(schemaSource.outputFiles[0].contents).toString("base64")}`
)

const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true } })
const validate = ajv.compile(registryItemSchema)
const generated = standalone(ajv, validate, { esm: true })

// Ajv's ESM emission still `require`s a few of its own runtime helpers —
// `ucs2length` for counting code points under `maxLength`. Bundling resolves
// those against the installed Ajv and inlines them, which is what makes the
// output a real ES module rather than one with a CommonJS hole in it. Nothing
// else is pulled in: the result is the schema's compiled code plus two helpers.
const bundled = await esbuild.build({
  stdin: { contents: generated, loader: "js", resolveDir: pkgRoot },
  bundle: true,
  minify: true,
  format: "esm",
  write: false,
  target: "es2022",
  legalComments: "none",
})
const code = bundled.outputFiles[0].text

// A CommonJS emission would silently break `import` for every consumer, and the
// generated file is not read by a human, so the guard belongs here.
if (!/\bexport\s*[{]/.test(code) && !/export (const|default) /.test(code)) {
  console.error(`[core] the standalone validator is not an ES module; refusing to write it.`)
  process.exit(1)
}

writeFileSync(srcFile, code)
// `dist/` may not exist yet: this script runs *before* `tsc`, since `tsc`
// compiles `src/validate-item.ts`, which imports the file written here. A warm
// checkout has `dist/` from an earlier build, which is why the missing
// directory only ever surfaced on a cold CI runner.
mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, code)

// TypeScript resolves `./registry-item-validator.js` to a sibling `.d.ts`, and
// the generated file has no types of its own. Writing the declaration here keeps
// the two in lockstep — a hand-maintained copy would be the thing that drifts.
writeFileSync(
  join(pkgRoot, "src", "registry-item-validator.d.ts"),
  `/**
 * Generated by scripts/build-validator.mjs. Do not edit.
 *
 * Ajv's standalone output for registry-item-v1: the schema's own compiled
 * validation code, with no Ajv at runtime.
 */
import type { ErrorObject } from "ajv/dist/2020.js"

declare const validate: ((data: unknown) => boolean) & { errors?: ErrorObject[] | null }
export default validate
`,
)

console.log(
  `[core] wrote src/registry-item-validator.js and dist/registry-item-validator.js (${Buffer.byteLength(code)} bytes, no runtime Ajv)`,
)
